#!/usr/bin/env python3
"""C for the host build from the matching build's gap objects (bytes no source file owns yet, see docs/unmatched.md).

Each data/rodata/bss section of a gap object becomes a u32 array with the original words; a word with an
R_ARM_ABS32 relocation becomes `(u32)&symbol + addend`, so pointers follow the host's addresses. The symbols the
object defines are placed into the array with `.set`. Functions can't be reused on the host: they are listed in a
comment, to be written in C (modern/host/gaps_code.c); data inside code sections is kept.

Usage: host_gaps.py <objects_aliases.txt> <out.c>
"""
import re
import struct
import sys

from elftools.elf.elffile import ELFFile
from elftools.elf.relocation import RelocationSection


def main():
    gaps = [l.strip().strip('"') for l in open(sys.argv[1]) if "/delinks/_dsd_gap@" in l]
    out = ["// generated by tools/host_gaps.py", "typedef unsigned int u32;", ""]
    code_syms, externs = [], set()
    defs = []
    for gi, path in enumerate(gaps):
        with open(path, "rb") as f:
            elf = ELFFile(f)
            symtab = elf.get_section_by_name(".symtab")
            for si, sec in enumerate(elf.iter_sections()):
                if sec["sh_type"] not in ("SHT_PROGBITS", "SHT_NOBITS") or not sec["sh_flags"] & 2 or sec["sh_size"] == 0:
                    continue
                names = [s for s in symtab.iter_symbols() if s["st_shndx"] == si and s.name and
                         s["st_info"]["type"] in ("STT_OBJECT", "STT_FUNC", "STT_NOTYPE")]
                if sec["sh_flags"] & 4:  # executable: the bytes are kept (data inside .text); functions need C
                    code_syms += [f"{s.name} ({path.split('@')[-1]})" for s in names
                                  if s["st_info"]["type"] == "STT_FUNC" and not s.name.startswith("$")]
                    names = [s for s in names if s["st_info"]["type"] != "STT_FUNC"]
                size = (sec["sh_size"] + 3) // 4 * 4
                data = sec.data() if sec["sh_type"] == "SHT_PROGBITS" else b"\0" * sec["sh_size"]
                data = data + b"\0" * (size - len(data))
                words = [f"{w:#x}u" for w in struct.unpack(f"<{size // 4}I", data)]
                for rs in elf.iter_sections():
                    if not isinstance(rs, RelocationSection) or rs["sh_info"] != si:
                        continue
                    for r in rs.iter_relocations():
                        if r["r_info_type"] != 2:  # R_ARM_ABS32
                            continue
                        sym = symtab.get_symbol(r["r_info_sym"])
                        add = r["r_addend"] if r.is_RELA() else struct.unpack_from("<I", data, r["r_offset"])[0]
                        if sym["st_info"]["type"] == "STT_SECTION" or not sym.name:
                            continue
                        externs.add(sym.name)
                        words[r["r_offset"] // 4] = f"(u32)&{sym.name} + {add:#x}"
                arr = f"host_gap{gi}_{si}"
                ro = "const " if sec["sh_flags"] & 1 == 0 else ""
                out.append(f"{ro}u32 {arr}[{size // 4}] __attribute__((aligned(4))) = {{ {', '.join(words)} }};")
                for s in names:
                    if not s.name.startswith(("$", ".L")):
                        defs.append(f'__asm__(".globl {s.name}\\n.set {s.name}, {arr} + {s["st_value"]}");')
    head = [f"extern char {n};" for n in sorted(externs)]
    out = out[:3] + head + [""] + out[3:] + [""] + defs
    out.append("")
    out.append("// code in gaps (written in C in modern/host/gaps_code.c): " + ", ".join(code_syms))
    open(sys.argv[2], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
