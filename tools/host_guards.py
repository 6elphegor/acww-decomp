#!/usr/bin/env python3
"""The guard variant of the host build's partial link: poisoned bytes after every variable (docs/portability.md 2.8).

Reads the map file of the ordinary partial link (`ld -r -Map`; the game compiled with -fdata-sections, so every
variable has its own section) and writes
- a linker script that places every input section of gdata, .rodata and gbss exactly where the ordinary link put it,
  each one followed by GUARD bytes (`__acww_guard_<i> = .; . += GUARD;`);
- a C table of the guards (modern/host/guards.c reads it): the guard's address, the variable's name (its section's
  name without the .data./.bss./.rodata. prefix), its size and its object file.

modern/host/guards.c fills the guards at start-up (ACWW_GUARDS_FILL, default 0xa5) and with ACWW_GUARDS=1 checks
them every frame: a changed guard is a write past the end of the variable before it. Runs with different fill
values (or ACWW_GUARDS_ALT, another fill for a range of guards) that behave differently show reads past an end.

Merged constants (.rodata.str*, .rodata.cst*) are left without guards (the linker merges them).

Usage: host_guards.py <map> <out.ld> <out.c> [--guard N] [--only LO-HI]
"""
import argparse
import re
from pathlib import Path

OUT_SECTIONS = ("gdata", ".rodata", "gbss")
KIND = {"gdata": 0, ".rodata": 1, "gbss": 2}


def parse_map(path):
    """[(output section, input section, size, file)] in map order (the output sections above only)."""
    out = []
    cur = None
    pending = None  # an input section name whose address/size/file are on the next line
    for line in Path(path).read_text(errors="replace").splitlines():
        if line and not line[0].isspace():
            name = line.split()[0]
            cur = name if name in OUT_SECTIONS else None
            pending = None
            continue
        if cur is None:
            continue
        if pending is not None:
            m = re.match(r"\s+0x([0-9a-f]+)\s+0x([0-9a-f]+)\s+(\S+)\s*$", line)
            if m:
                out.append((cur, pending, int(m.group(2), 16), m.group(3)))
            pending = None
            continue
        m = re.match(r" ([^\s*][^\s]*)(?:\s+0x([0-9a-f]+)\s+0x([0-9a-f]+)\s+(\S+))?\s*$", line)
        if not m:
            continue
        if m.group(2) is None:
            pending = m.group(1)
        else:
            out.append((cur, m.group(1), int(m.group(3), 16), m.group(4)))
    return out


def var_name(sec):
    for p in (".data.rel.ro.local.", ".data.rel.ro.", ".data.rel.local.", ".data.rel.", ".data.", ".bss.", ".rodata."):
        if sec.startswith(p):
            return sec[len(p):]
    return sec


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("map")
    ap.add_argument("out_ld")
    ap.add_argument("out_c")
    ap.add_argument("--guard", type=int, default=64)
    ap.add_argument("--only", metavar="LO-HI",
                    help="guards only after the variables LO..HI-1 (in map order): bisecting a layout dependence")
    a = ap.parse_args()
    lo, hi = (int(x) for x in a.only.split("-")) if a.only else (0, 1 << 30)
    n = 0
    entries = parse_map(a.map)
    seen = set()
    body = {s: [] for s in OUT_SECTIONS}
    guards = []
    for osec, isec, size, f in entries:
        if (f, isec) in seen:
            continue
        seen.add((f, isec))
        merged = isec.startswith((".rodata.str", ".rodata.cst"))
        if merged:
            continue  # (placed by the catch-all lines)
        body[osec].append(f"        {f}({isec})")
        if size and osec in KIND:
            n += 1
            if not lo <= n - 1 < hi:
                continue
            i = len(guards)
            guards.append((i, KIND[osec], var_name(isec), size, f))
            body[osec].append(f"        __acww_guard_{i} = .; . += {a.guard};")
    rest = {"gdata": "*(.data .data.*)", ".rodata": "*(.rodata .rodata.*)", "gbss": "*(.bss .bss.* COMMON)"}
    script = ["/* generated by tools/host_guards.py */", "SECTIONS", "{"]
    for s in OUT_SECTIONS:
        script += [f"    {s} : {{"] + body[s] + [f"        {rest[s]}", "    }"]
    script.append("}")
    Path(a.out_ld).write_text("\n".join(script) + "\n")
    c = ["/* generated by tools/host_guards.py */", "#include \"guards.h\"", ""]
    c += [f"extern char __acww_guard_{i}[];" for i, *_ in guards]
    c += ["", f"const unsigned host_guard_size = {a.guard};", f"const unsigned host_guard_count = {len(guards)};",
          "const HostGuard host_guard_table[] = {"]
    for i, kind, name, size, f in guards:
        c.append(f'    {{__acww_guard_{i}, {kind}, {size:#x}, "{name}", "{Path(f).name}"}},')
    c.append("};")
    Path(a.out_c).write_text("\n".join(c) + "\n")


if __name__ == "__main__":
    main()
