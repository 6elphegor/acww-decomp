#!/usr/bin/env python3
"""Linker script for the host build's partial link: the game's variables in their original order, and each
overlay's data, bss and constructors in ranges of their own.

The decompiled code sometimes reaches one variable from another (a clear or copy that spans two arrays, a table
indexed past its end): that works in the original layout. The game objects are compiled with -fdata-sections; this
script places each variable's section (.data.<name>, .bss.<name>, .rodata.<name>) in the order of the original
addresses (symbols.txt of each module, grouped by module), the rest after them. The data and bss go to `gdata` and
`gbss`, which the final link places in DS main RAM (0x02000000 and 0x02040000, configure_host.py), where the ARM7
can reach them. See docs/host.md.

Overlays: the DS reads an overlay's code and data from the ROM each time it is loaded, clears its bss and runs its
static constructors; the host has every overlay linked in, so loading one resets its variables instead
(modern/host/overlay.c). For that, the sections of the objects under src/ovNNN/ go to one range per overlay: in
gdata between host_ovNNN_data_start and host_ovNNN_data_end (the variables of symbols.txt first, in their order, then
the overlay's other data; an overlay variable that a source outside src/ovNNN defines stays after the range, where it
was), in gbss between host_ovNNN_bss_start/_end, and the overlay's .init_array entries (in object
order, as the DS's .sinit list) to the section host_ovinit between host_ovNNN_init_start/_end - not to .init_array,
so they don't run at start-up (on the DS they run only when the overlay is loaded). The other modules' statements
exclude the overlay objects. The table of the ranges for the runtime is written as C (<out_table.c>).

Usage: host_order.py <config dir> <out.ld> <out_table.c>
"""
import os
import re
import sys
from pathlib import Path

OV_FILES = "*/src/ov[0-9][0-9][0-9]/*"


def main():
    config, out, table = Path(sys.argv[1]), sys.argv[2], sys.argv[3]
    files = [config / "symbols.txt"] + sorted(config.glob("*/symbols.txt")) + sorted(config.glob("overlays/*/symbols.txt"))
    order = []
    module_of = {}
    for mi, f in enumerate(files):
        m = re.match(r"ov(\d{3})$", f.parent.name) if f.parent.parent.name == "overlays" else None
        module_of[mi] = int(m.group(1)) if m else None
        for line in f.read_text().splitlines():
            m = re.match(r"(\S+) kind:(data|bss)\S* addr:0x([0-9a-f]+)", line)
            if m:
                order.append((mi, int(m.group(3), 16), m.group(1)))
    order.sort()
    # the overlays with sources (src/ovNNN; the id is the number)
    overlays = sorted(int(d.name[2:]) for d in Path("src").iterdir() if re.match(r"ov\d{3}$", d.name) and d.is_dir())
    # names per overlay (in address order) and the others (main, autoloads, ITCM; DTCM is linked apart)
    names_main = []
    names_ov = {n: [] for n in overlays}
    seen_main, seen_ov = set(), set()
    for mi, _, name in order:
        ov = module_of[mi]
        if ov is None:
            if name not in seen_main:
                seen_main.add(name)
                names_main.append(name)
        elif ov in names_ov and (ov, name) not in seen_ov:
            seen_ov.add((ov, name))
            names_ov[ov].append(name)

    def main_block(prefix):
        return "\n".join(f"        *(EXCLUDE_FILE({OV_FILES}) {prefix}.{n})" for n in names_main)

    def ov_block(prefix, kind, rest):
        lines = []
        for ov in overlays:
            pat = f"*/src/ov{ov:03d}/*"
            lines.append(f"        host_ov{ov:03d}_{kind}_start = .;")
            lines += [f"        {pat}({prefix}.{n})" for n in names_ov[ov]]
            lines.append(f"        {pat}({rest})")
            lines.append(f"        host_ov{ov:03d}_{kind}_end = .;")
            # the overlay's variables that a source outside the overlays defines: where they were (not reset)
            lines += [f"        *(EXCLUDE_FILE({OV_FILES}) {prefix}.{n})" for n in names_ov[ov] if n not in seen_main]
        return "\n".join(lines)

    rodata = "\n".join(f"        *(.rodata.{n})" for n in names_main + [n for ov in overlays for n in names_ov[ov]])
    inits = []
    for ov in overlays:
        inits.append(f"        host_ov{ov:03d}_init_start = .;")
        inits.append(f"        KEEP(*/src/ov{ov:03d}/*(.init_array .init_array.*))")
        inits.append(f"        host_ov{ov:03d}_init_end = .;")
    script = f"""/* generated by tools/host_order.py */
SECTIONS
{{
    gdata : {{
{main_block('.data')}
{ov_block('.data', 'data', '.data .data.*')}
        *(.data .data.*)
    }}
    .rodata : {{
{rodata}
        *(.rodata .rodata.*)
    }}
    gbss : {{
{main_block('.bss')}
{ov_block('.bss', 'bss', '.bss .bss.* COMMON')}
        *(.bss .bss.* COMMON)
    }}
    host_ovinit : {{
{chr(10).join(inits)}
    }}
}}
"""
    Path(out).write_text(script)

    # the table for modern/host/overlay.c
    c = ["// generated by tools/host_order.py: each overlay's data, bss and constructors (ranges in the game object)",
         '#include "overlay.h"', ""]
    for ov in overlays:
        c.append(f"extern char host_ov{ov:03d}_data_start[], host_ov{ov:03d}_data_end[], host_ov{ov:03d}_bss_start[], "
                 f"host_ov{ov:03d}_bss_end[];")
        c.append(f"extern HostOverlayCtor host_ov{ov:03d}_init_start[], host_ov{ov:03d}_init_end[];")
    c.append("")
    c.append("const HostOverlayRanges gHostOverlays[] = {")
    for ov in overlays:
        p = f"host_ov{ov:03d}"
        c.append(f"    {{{ov}, {p}_data_start, {p}_data_end, {p}_bss_start, {p}_bss_end, {p}_init_start, {p}_init_end}},")
    c.append("};")
    c.append(f"const unsigned gHostOverlayCount = {len(overlays)};")
    Path(table).write_text("\n".join(c) + "\n")


if __name__ == "__main__":
    main()
