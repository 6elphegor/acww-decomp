#!/usr/bin/env python3
"""Thunks for calls to addresses that several overlays share (modern build, see docs/modern.md, "Shared overlay
addresses").

The original holds fixed addresses inside overlays (main's player action tables, callbacks, mode tables). Several
overlays are loaded at the same address, and the address means the function of whichever is loaded. The decompiled
code names it after one of them; the modern build places overlays elsewhere and would always call the named one.

For every reference from an object to a function of another module whose address another overlay also uses (from
the overlays' symbols.txt), this writes:
  * a thunk `__wrap_<name>` (ARM): Modern_SharedResolve (modern/ds/overlays.c) picks the candidate whose overlay is
    loaded, the named one first; the thunk jumps there with the arguments untouched;
  * the `--wrap=<name>` linker option, which sends the references (not the definition) to the thunk.
Candidates other than the named one are weak references: a name the modern build doesn't define resolves to 0 and
is skipped. References to data at shared addresses are listed on stderr; they need a look.

Usage: modern_shared.py --nm <nm> --objects <objects.txt> --config <config/usa/arm9> --asm <out.s> --wrap <out.txt>
"""
import argparse
import re
import subprocess
from collections import defaultdict
from pathlib import Path


def module_of(obj: str) -> str:
    m = re.search(r"/src/(ov\d+)/", obj)
    return m.group(1) if m else "static"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nm", required=True)
    ap.add_argument("--objects", required=True)
    ap.add_argument("--config", required=True, type=Path)
    ap.add_argument("--asm", required=True)
    ap.add_argument("--wrap", required=True)
    ap.add_argument("--arch", default="arm", choices=["arm", "x86"], help="thunk code: the DS (ARM) or the host build")
    args = ap.parse_args()

    by_addr = defaultdict(list)  # address -> [(overlay, name, kind)]
    owner = {}
    for f in sorted((args.config / "overlays").glob("*/symbols.txt")):
        ov = f.parent.name
        for line in f.read_text().splitlines():
            m = re.match(r"(\S+) kind:(\w+)\S* addr:0x([0-9a-f]+)", line)
            if m:
                a = int(m.group(3), 16)
                by_addr[a].append((ov, m.group(1), m.group(2)))
                owner.setdefault(m.group(1), (ov, a, m.group(2)))

    objects = [l.strip() for l in open(args.objects) if l.strip() and "/gaps/" not in l]
    out = subprocess.run([args.nm, "-u", "-A", *objects], capture_output=True, text=True).stdout
    defined = set(subprocess.run([args.nm, "--defined-only", "-j", *objects], capture_output=True,
                                 text=True).stdout.split())
    wrapped, data_refs = {}, set()
    for line in out.splitlines():
        obj, _, name = line.rpartition(" ")
        obj = obj.split(":")[0]
        if name not in owner:
            continue
        ov, a, kind = owner[name]
        others = [(o, n, k) for o, n, k in by_addr[a] if o != ov]
        if not others or module_of(obj) == ov:
            continue
        if kind != "function":
            data_refs.add(f"{obj}: {name} ({ov} {a:#x}; also {', '.join(f'{o}:{n}' for o, n, _ in others[:3])})")
            continue
        wrapped[name] = (ov, a, [(o, n) for o, n, k in others if k == "function"])

    x86 = args.arch == "x86"
    asm = ["# generated by tools/modern_shared.py", "    .text"] if x86 else \
          ["@ generated by tools/modern_shared.py", "    .syntax unified", "    .arm"]
    for name, (ov, a, others) in sorted(wrapped.items()):
        def ref(n):
            # the DS build wraps in its final link (__real_ is the original); the host build in its partial link,
            # so at the final link the original keeps its own name
            return f"__real_{n}" if n in wrapped and not x86 else n
        cands = [(ov, name)] + [(o, n) for o, n in others if n in defined or n in wrapped]
        if x86:  # cdecl: the arguments stay on the stack; eax/ecx/edx are free at entry
            asm += [f"    .section .text.__wrap_{name},\"ax\",@progbits", "    .align 4",
                    f"    .globl __wrap_{name}", f"    .type __wrap_{name}, @function", f"__wrap_{name}:",
                    f"    pushl $.L{name}_tab", "    call Modern_SharedResolve", "    addl $4, %esp", "    jmp *%eax",
                    f".L{name}_tab:", f"    .long {len(cands)}"]
            for o, n in cands:
                asm.append(f"    .long {int(o[2:])}, {ref(n)}")
        else:
            asm += [f"    .section .text.__wrap_{name},\"ax\",%progbits", "    .align 2",
                    f"    .global __wrap_{name}", f"    .type __wrap_{name}, %function", f"__wrap_{name}:",
                    "    push {r0-r3, r12, lr}", f"    adr r0, .L{name}_tab", "    bl Modern_SharedResolve",
                    "    str r0, [sp, #16]", "    pop {r0-r3, r12, lr}", "    bx r12",
                    f".L{name}_tab:", f"    .word {len(cands)}"]
            for o, n in cands:
                asm.append(f"    .word {int(o[2:])}, {ref(n)}")
        for o, n in cands[1:]:
            if n not in wrapped:
                asm.append(f"    .weak {n}")
        asm.append(f"    .size __wrap_{name}, . - __wrap_{name}")
    Path(args.asm).write_text("\n".join(asm) + "\n")
    Path(args.wrap).write_text("".join(f"{'' if x86 else '-Wl,'}--wrap={n}\n" for n in sorted(wrapped)))
    for d in sorted(data_refs):
        print(f"modern_shared.py: data at a shared overlay address: {d}")
    print(f"modern_shared.py: {len(wrapped)} thunks")


if __name__ == "__main__":
    main()
